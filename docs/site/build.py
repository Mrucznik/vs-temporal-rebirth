#!/usr/bin/env python3
"""Writes docs/site/shaders.js: the mod's own GLSL shaders, made to compile in WebGL 2, for the live demo on the site.

Run it again after changing anything in assets/temporalrebirth/shaders/, then reload the page.
"""
import json, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SHADERS = REPO / "assets/temporalrebirth/shaders"

# The shaders include the game's noise3d.ash for valuenoise(). The page does not ship game files, so it gets this
# stand-in: the same well-known public value noise (perm-based, mod 289), giving the same numbers.
NOISE = """
float cmod289(float x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 cmod289(vec4 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 perm(vec4 x) { return cmod289(((x * 34.0) + 1.0) * x); }
float valuenoise(vec3 p) {
  vec3 a = floor(p);
  vec3 d = p - a;
  d = d * d * (3.0 - 2.0 * d);
  vec4 b = a.xxyy + vec4(0.0, 1.0, 0.0, 1.0);
  vec4 k1 = perm(b.xyxy);
  vec4 k2 = perm(k1.xyxy + b.zzww);
  vec4 c = k2 + a.zzzz;
  vec4 k3 = perm(c);
  vec4 k4 = perm(c + 1.0);
  vec4 o1 = fract(k3 * (1.0 / 41.0));
  vec4 o2 = fract(k4 * (1.0 / 41.0));
  vec4 o3 = o2 * d.z + o1 * (1.0 - d.z);
  vec2 o4 = o3.yw * d.x + o3.xz * (1.0 - d.x);
  return o4.y * d.y + o4.x * (1.0 - d.y);
}
"""
INCLUDES = {"noise3d.ash": NOISE}


def source(path):
    """The game's GLSL 3.30 as WebGL 2 takes it."""
    text = path.read_text(encoding="utf8").replace("#version 330 core", "#version 300 es\nprecision highp float;\nprecision highp int;")
    text = re.sub(r"^#extension .*$", "", text, flags=re.M)

    def include(m):
        if m[1] not in INCLUDES:
            raise SystemExit(f"{path.name}: no stand-in for #include {m[1]}; add one to docs/site/build.py")
        return INCLUDES[m[1]]

    return re.sub(r"^#include\s+(\S+)", include, text, flags=re.M)


def main():
    shaders = {p.name: source(p) for p in sorted(SHADERS.iterdir()) if p.suffix in (".vsh", ".fsh")}
    out = HERE / "shaders.js"
    out.write_text("// Generated by docs/site/build.py from assets/temporalrebirth/shaders/. Do not edit; run the script again.\n"
                   "window.TR_SHADERS = " + json.dumps(shaders, indent=1) + ";\n", encoding="utf8")
    print(out, ", ".join(shaders))


if __name__ == "__main__":
    main()
